"""Generate docs/explain.md: EXPLAIN output for key queries with and without the
secondary indexes from db/006_indexes.sql (evidence that the indexes are used).

    python scripts/explain_report.py

"Without" uses an IGNORE INDEX hint, so nothing is dropped (some of these
indexes also back foreign keys and cannot be dropped).
"""
import sys
from pathlib import Path

sys.path[:0] = [str(Path(__file__).resolve().parents[1]), str(Path(__file__).resolve().parent)]
import migrate  # noqa: E402
from app.settings import ROOT  # noqa: E402

CASES = [
    ("Browse: Open projects by deadline", "ix_project_status", "Project", "(status, deadline)",
     "SELECT p_id, p_name FROM Project {hint} WHERE status = 'Open' ORDER BY deadline"),
    ("Owner review queue: applications of a project by status", "ix_application_proj", "Application", "(p_id, status)",
     "SELECT a_id FROM Application {hint} WHERE p_id = 1 AND status = 'Pending'"),
    ("Candidate prefilter: users holding a skill at a level", "ix_uhs_skill", "user_has_skill", "(s_id, u_s_level)",
     "SELECT u_id FROM user_has_skill {hint} WHERE s_id = 16 AND u_s_level IN ('Advanced','Expert')"),
    ("My tasks: tasks of a user by status", "ix_task_user", "Task", "(u_id, status)",
     "SELECT task_id FROM Task {hint} WHERE u_id = 9 AND status <> 'Done'"),
    ("Domain filter", "ix_domain_name", "Domain", "(d_name)",
     "SELECT project_id FROM Domain {hint} WHERE d_name = 'Web'"),
]
COLS = ["type", "possible_keys", "key", "rows", "Extra"]


def explain(cur, sql: str) -> list[dict]:
    cur.execute("EXPLAIN " + sql)
    names = [d[0] for d in cur.description]
    return [dict(zip(names, row)) for row in cur.fetchall()]


def table(rows: list[dict]) -> str:
    head = "| " + " | ".join(COLS) + " |\n|" + "---|" * len(COLS) + "\n"
    return head + "".join("| " + " | ".join(str(r.get(c) if r.get(c) is not None else "") for c in COLS) + " |\n" for r in rows)


def main() -> None:
    conn = migrate.connect("teamtree")
    out = ["# EXPLAIN: secondary indexes in use", "",
           "Generated by `api/scripts/explain_report.py` against the seed data. For each query the plan is shown",
           "with the index (as deployed) and with `IGNORE INDEX (...)`. With the tiny seed the optimizer",
           "may still prefer a scan for some queries; `key` shows which index was actually chosen.", ""]
    with conn.cursor() as cur:
        for title, index, tbl, cols, sql in CASES:
            with_idx = explain(cur, sql.format(hint=""))
            without = explain(cur, sql.format(hint=f"IGNORE INDEX ({index})"))
            out += [f"## {title}", "", f"`{index}` on `{tbl}{cols}`", "", "```sql", sql.format(hint="") + ";", "```", "",
                    "**With the index**", "", table(with_idx), f"**IGNORE INDEX ({index})**", "", table(without)]
    conn.close()
    path = ROOT / "docs" / "explain.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
